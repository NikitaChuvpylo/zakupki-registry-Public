// Справочник единиц измерения -> код ОКЕИ
// Источник: Общероссийский классификатор единиц измерения (ОК 015-94)
// Коды для типовых единиц из спецификаций продуктовых контрактов
const OKEI = {
  // масса
  'кг': 166, 'килограмм': 166, 'килограмма': 166, 'килограмм': 166, 'кг.': 166,
  'г': 163, 'грамм': 163, 'г.': 163,
  'т': 168, 'тонна': 168, 'тонн': 168, 'т.': 168,
  // объём
  'л': 112, 'литр': 112, 'литра': 112, 'литров': 112, 'л.': 112,
  'мл': 111, 'миллилитр': 111,
  'дм3': 110, 'куб. дм': 110,
  // штуки
  'шт': 796, 'штука': 796, 'штуки': 796, 'штук': 796, 'шт.': 796,
  'упак': 778, 'упаковка': 778, 'упаковки': 778, 'упаковок': 778, 'уп.': 778,
  'пач': 778,
  'банка': 778, 'банки': 778, 'банок': 778,
  'бутылка': 778, 'бутылки': 778, 'бутылок': 778,
  // длина/прочее
  'м': 6, 'метр': 6,
  'м2': 55, 'кв. м': 55, 'кв.м': 55,
  'компл': 839, 'комплект': 839, 'комплекта': 839, 'комплектов': 839,
  'усл. ед': 876, 'условная единица': 876,
  'мес': 362, 'месяц': 362,
  'год': 366, 'г.услуга': 366,
  'чел': 792, 'человек': 792,
};

const norm = (s) => String(s || '').trim().toLowerCase().replace(/\.+$/, '').replace(/\s+/g, ' ');

function unitCode(unit) {
  const n = norm(unit);
  if (OKEI[n]) return OKEI[n];
  // частичное совпадение: «литр», «килограмм» внутри фразы
  if (/литр/.test(n)) return 112;
  if (/килограмм|кг/.test(n)) return 166;
  if (/грамм/.test(n)) return 163;
  if (/тонн/.test(n)) return 168;
  if (/штук|шт/.test(n)) return 796;
  if (/упаков|пачк|банк|бутыл|порц/.test(n)) return 778;
  return '';
}

module.exports = { unitCode, OKEI };
